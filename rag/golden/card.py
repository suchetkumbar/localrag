"""Statistics for the data card, computed from the dataset files themselves.

The numbers in data/golden/README.md are generated by ``python -m rag.golden build`` and
written between marker comments, so the card can never drift from the data.
"""

import re
from collections import Counter
from collections.abc import Sequence
from pathlib import Path

from rag.golden.schema import QUESTION_TYPES, GoldenItem

START = "<!-- stats:start (generated by `python -m rag.golden build`; do not edit) -->"
END = "<!-- stats:end -->"


def stats_markdown(dataset: Sequence[GoldenItem], drafts: Sequence[GoldenItem]) -> str:
    by_type = Counter(i.question_type for i in dataset)
    statuses = Counter(i.review.status for i in drafts)
    edited = sum(1 for i in dataset if i.review.status == "edited")
    docs = {e.doc_id for i in dataset for e in i.evidence}
    spans = [len(i.evidence) for i in dataset if i.evidence]
    fingerprints = sorted({i.corpus_fingerprint for i in dataset})
    drafters = Counter(i.provenance.drafted_by for i in dataset)

    lines = [
        "| Question type | Items | Share |",
        "|---|---:|---:|",
    ]
    total = len(dataset)
    for q in QUESTION_TYPES:
        share = f"{by_type[q] / total:.0%}" if total else "n/a"
        lines.append(f"| {q} | {by_type[q]} | {share} |")
    lines.append(f"| **total** | **{total}** | |")
    lines += [
        "",
        f"- Human-verified: {sum(i.human_verified for i in dataset)} of {total}"
        f" ({edited} edited by the reviewer before acceptance)",
        f"- Review of {len(drafts)} LLM drafts: {statuses['accepted']} accepted as-is,"
        f" {statuses['edited']} edited, {statuses['rejected']} rejected,"
        f" {statuses['pending']} not yet reviewed",
        f"- Documents with evidence: {len(docs)}",
        f"- Evidence spans per answerable item: mean {sum(spans) / len(spans):.2f}"
        if spans
        else "- Evidence spans per answerable item: n/a",
        f"- Drafted by: {', '.join(f'{k} ({v})' for k, v in drafters.most_common()) or 'n/a'}",
        f"- Corpus fingerprint: `{', '.join(fingerprints) or 'n/a'}`",
    ]
    return "\n".join(lines)


def update_card(card: Path, stats: str) -> None:
    text = card.read_text(encoding="utf-8")
    block = f"{START}\n{stats}\n{END}"
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.DOTALL)
    if not pattern.search(text):
        raise ValueError(f"{card} has no stats markers")
    card.write_text(pattern.sub(lambda _: block, text), encoding="utf-8", newline="\n")
