"""The configuration matrix: chunker x retriever x reranker, derived from one base config.

Both chunkers cap chunks at the same size (1000 characters, 150 overlap), so the
chunking comparison is about *where* boundaries fall (fixed windows vs markdown
sections), not about chunk size.
"""

import json
import re
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

from rag.config import PipelineConfig

CHUNKERS: dict[str, dict[str, Any]] = {
    "fixed": {"kind": "fixed", "size": 1000, "overlap": 150},
    "heading": {"kind": "heading", "max_heading_level": 3, "max_size": 1000, "overlap": 150},
}
RETRIEVERS = ("dense", "bm25", "hybrid")
RERANKER = {"kind": "cross_encoder", "model": "BAAI/bge-reranker-base"}

README_START = "<!-- results:start (generated by `rag-eval matrix`; do not edit) -->"
README_END = "<!-- results:end -->"
COLUMNS = ("recall@5", "mrr", "ndcg@10", "accuracy", "faithfulness", "refusal_accuracy")


def matrix_configs(base: PipelineConfig) -> list[PipelineConfig]:
    variants = []
    for chunker_name, chunker in CHUNKERS.items():
        for retriever in RETRIEVERS:
            for rerank in (False, True):
                name = f"{chunker_name}-{retriever}" + ("-rerank" if rerank else "")
                data = base.model_dump(mode="json")
                data.update(
                    name=name,
                    chunker=chunker,
                    reranker=RERANKER if rerank else None,
                    retrieval={**data["retrieval"], "retriever": {"kind": retriever}},
                )
                variants.append(PipelineConfig.model_validate(data))
    return variants


def _cell(intervals: Mapping[str, Any], metric: str) -> str:
    iv = intervals.get(metric)
    if iv is None:
        return "n/a"
    return f"{iv['mean']:.3f} [{iv['low']:.2f}, {iv['high']:.2f}]"


def summary_table(run_dirs: Sequence[Path]) -> tuple[str, bool]:
    """Markdown table of all runs, and whether every run is a full, verified run."""
    lines = [
        "| Config | " + " | ".join(COLUMNS) + " | p50 answer latency |",
        "|---|" + "---:|" * (len(COLUMNS) + 1),
    ]
    publishable = True
    for run_dir in run_dirs:
        payload = json.loads((run_dir / "metrics.json").read_text(encoding="utf-8"))
        run, intervals = payload["run"], payload["intervals"]
        publishable &= run["dataset"]["all_verified"] and run["mode"] == "full"
        latency = payload["metrics"]["latency_ms"].get("model_latency_ms")
        p50 = f"{latency['p50'] / 1000:.1f} s" if latency else "n/a"
        cells = " | ".join(_cell(intervals, m) for m in COLUMNS)
        lines.append(
            f"| [`{run['config_name']}`]({run_dir.as_posix()}/report.md) | {cells} | {p50} |"
        )
    return "\n".join(lines), publishable


def write_summary(run_dirs: Sequence[Path], out: Path, readme: Path | None) -> bool:
    """Write the matrix summary; update the README only for full, verified runs."""
    table, publishable = summary_table(run_dirs)
    header = "# Configuration matrix\n\nMean [95% bootstrap CI] over golden items.\n\n"
    if not publishable:
        header += (
            "> **Not publishable:** at least one run used unverified items or skipped "
            "generation. The README was not updated.\n\n"
        )
    out.write_text(header + table + "\n", encoding="utf-8", newline="\n")
    if readme is not None and publishable:
        text = readme.read_text(encoding="utf-8")
        pattern = re.compile(re.escape(README_START) + ".*?" + re.escape(README_END), re.DOTALL)
        if not pattern.search(text):
            raise ValueError(f"{readme} has no results markers")
        source = out.as_posix()
        block = f"{README_START}\n{table}\n\nSource: [`{source}`]({source})\n{README_END}"
        readme.write_text(pattern.sub(lambda _: block, text), encoding="utf-8", newline="\n")
    return publishable
